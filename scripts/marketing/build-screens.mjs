#!/usr/bin/env node
/**
 * Landing v2 — turn the real app captures used in the promo video into web assets.
 *
 *   node scripts/marketing/build-screens.mjs
 *
 * Source: promo-video/screenshots/v4 (real demo-org captures; desktop 2×, mobile 3×) and the
 * measured boxes in promo-video/screenshots/v6/boxes.json. promo-video/ is git-ignored, so this
 * script runs locally; its outputs (public/marketing/screens/*.webp and lib/marketing/screens.ts)
 * are committed. Nothing is redrawn: images are only cropped and re-encoded.
 */
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "../..");
const SRC = path.join(ROOT, "promo-video/screenshots/v4");
const OUT = path.join(ROOT, "public/marketing/screens");
const BOX = JSON.parse(fs.readFileSync(path.join(ROOT, "promo-video/screenshots/v6/boxes.json"), "utf8"));
// pricing-page card boxes measured at capture time (default rate card + season card)
const PRICE_BOX = JSON.parse(fs.readFileSync(path.join(ROOT, "promo-video/screenshots/v4/boxes-pricing.json"), "utf8"))["m-pricing-430"];
const PHONE_ASPECT = 844 / 390;

// key, source file, CSS width of the capture, device pixel ratio, window top (CSS px) for phone crops
const SHOTS = [
  { key: "dashboard", file: "d-dashboard.png", cw: 1440, dpr: 2 },
  { key: "cal-base", file: "cal-0-base.png", cw: 1440, dpr: 2 },
  { key: "cal-start", file: "cal-1-start.png", cw: 1440, dpr: 2 },
  { key: "cal-hover", file: "cal-2-hover-booking.png", cw: 1440, dpr: 2 },
  { key: "cal-dialog", file: "cal-3-dialog.png", cw: 1440, dpr: 2 },
  { key: "pricing", file: "m-pricing-430.png", cw: 430, dpr: 3, top: 1780 },
  { key: "payments", file: "m-payments.png", cw: 390, dpr: 3, top: 150 },
  { key: "cashbox", file: "m-cashier.png", cw: 390, dpr: 3, top: 1300 },
  { key: "invoice", file: "m-invoice.png", cw: 390, dpr: 3, top: 330 },
  { key: "overdue", file: "m-invoices-overdue.png", cw: 390, dpr: 3, top: 300 },
];

// Focus / glow rects in CSS px of the full capture (same numbers the video uses: build6.py SHOTS + boxes.json).
const A = BOX.anim;
const FOCUS = {
  dashboard: Object.fromEntries(Object.entries(A.dashboard).map(([k, r]) => [k, r])),
  calendar: A.calendar,
  pricing: A.glow.price,
  payments: A.glow.pay,
  cashbox: A.glow.cash,
  invoice: A.glow.inv,
  overdue: A.glow.over,
};

const shift = (r, dy) => [r[0], +(r[1] - dy).toFixed(1), r[2], r[3]];

const manifest = {};
for (const s of SHOTS) {
  const img = sharp(path.join(SRC, s.file));
  const meta = await img.metadata();
  const cssH = meta.height / s.dpr;
  let top = 0, winH = cssH;
  if (s.top !== undefined) {                      // phone: one screen-shaped window around the focus
    winH = Math.round(s.cw * PHONE_ASPECT);
    top = Math.max(0, Math.min(s.top, cssH - winH));
  }
  const out = path.join(OUT, `${s.key}.webp`);
  await sharp(path.join(SRC, s.file))
    .extract({ left: 0, top: Math.round(top * s.dpr), width: meta.width, height: Math.round(winH * s.dpr) })
    .webp({ quality: 84, effort: 6 })
    .toFile(out);
  const sz = fs.statSync(out).size;
  manifest[s.key] = { src: `/marketing/screens/${s.key}.webp`, width: meta.width, height: Math.round(winH * s.dpr), cssWidth: s.cw, cssHeight: Math.round(winH), cropTop: top };
  console.log(`${s.key.padEnd(10)} ${meta.width}×${Math.round(winH * s.dpr)}  ${(sz / 1024).toFixed(0)} KB`);
}

// rects re-based to each crop (CSS px of the cropped screen)
const rebase = (key, r) => shift(r, manifest[key].cropTop);
const C = FOCUS.calendar;
const focus = {
  dashboard: Object.fromEntries(Object.entries(FOCUS.dashboard).map(([k, r]) => [k, rebase("dashboard", r)])),
  calendar: { startCell: C.start_cell, endCell: C.end_cell, firstOccupied: C.first_occupied, redPulse: C.red_pulse,
              dialog: C.dialog, createButton: C.create_btn, popover: C.popover, view: FOCUS.calendar ? A.glow.cal.focus : null },
  pricing: { key: rebase("pricing", FOCUS.pricing.key), view: rebase("pricing", FOCUS.pricing.focus),
             defaultCard: rebase("pricing", PRICE_BOX.default.card), seasonCard: rebase("pricing", PRICE_BOX.season.card) },
  payments: { key: rebase("payments", FOCUS.payments.key), view: rebase("payments", FOCUS.payments.focus) },
  cashbox: { key: rebase("cashbox", FOCUS.cashbox.key), view: rebase("cashbox", FOCUS.cashbox.focus) },
  invoice: { key: rebase("invoice", FOCUS.invoice.key), view: rebase("invoice", FOCUS.invoice.focus) },
  overdue: { key: rebase("overdue", FOCUS.overdue.key), view: rebase("overdue", FOCUS.overdue.focus) },
};

const ts = `/* GENERATED by scripts/marketing/build-screens.mjs — do not edit by hand.
 * Real Binaya app captures (demo organisation), cropped only. Rects are [x, y, w, h] in CSS px of each screen. */

export type Rect = readonly [number, number, number, number];
export type Screen = { src: string; width: number; height: number; cssWidth: number; cssHeight: number; cropTop: number };

export const SCREENS = ${JSON.stringify(manifest, null, 2)} as const satisfies Record<string, Screen>;

export const FOCUS = ${JSON.stringify(focus, null, 2)} as const;
`;
fs.writeFileSync(path.join(ROOT, "lib/marketing/screens.ts"), ts);
console.log("wrote lib/marketing/screens.ts");

// Photos (Unsplash licence, logged in promo-video/images/LICENSE-v6.txt): resized only, no AI edits.
fs.mkdirSync(path.join(ROOT, "public/marketing/photos"), { recursive: true });
for (const [src, out] of [["promo-video/images/v6-bedroom.jpg", "public/marketing/photos/bedroom.webp"]]) {
  await sharp(path.join(ROOT, src)).resize({ width: 1920 }).webp({ quality: 72, effort: 6 }).toFile(path.join(ROOT, out));
  console.log(`${out}  ${(fs.statSync(path.join(ROOT, out)).size / 1024).toFixed(0)} KB`);
}
